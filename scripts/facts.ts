// Writes docs/FACTS.json: every number the README, UI and video may show, each traced to the run
// or file it came from. `--check` fails if the committed FACTS.json differs from a fresh build
// (CI runs it), so no number can drift from its source.
import { readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync } from "node:fs";

function read(p: string): any | null {
  return existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : null;
}

export function buildFacts() {
  const sources = read("data/sources.json");
  const replay = read("data/replay.json");
  const deployment = read("deployments/testnet.json");
  const runs = read("data/runs.json");
  const byId = Object.fromEntries((sources?.facts ?? []).map((f: any) => [f.id, f]));
  const w = replay?.window_2023_2025;
  return {
    _note: "Generated by scripts/facts.ts. Do not edit by hand.",
    world: {
      seafarers_abandoned_2025: byId.itf_2025_seafarers_abandoned?.value ?? null,
      ships_abandoned_2025: byId.itf_2025_ships?.value ?? null,
      owed_usd_2025: byId.itf_2025_owed_usd?.value ?? null,
      recovered_usd_2025: byId.itf_2025_recovered_usd?.value ?? null,
      indian_seafarers_2025: byId.itf_2025_indian_seafarers?.value ?? null,
      insurer_months_to_pay: byId.insurer_eight_months?.value ?? null,
      longest_case_months: byId.imo_longest_case_months?.value ?? null,
      mlc_trigger_months: byId.mlc_abandonment_trigger_months?.value ?? null,
      mlc_cover_months: byId.mlc_security_wage_months?.value ?? null,
      source: "data/sources.json",
    },
    replay: w
      ? {
          window: "2023 to 2025",
          source: replay.source,
          retrieved: replay.retrieved,
          cases_replayed: w.cases_replayed,
          cases_excluded_missing_data: w.cases_excluded_missing_data,
          seafarers: w.seafarers,
          share_on_board_pct: w.share_on_board_pct,
          cases_fully_covered: w.cases_fully_covered,
          cases_partial_miss: w.cases_partial_miss,
          largest_partial_misses: w.partial_misses.slice(0, 5).map((p: any) => `${p.vessel} (IMO ${p.imo}): ${p.months_owed} months owed, ${p.seafarers} crew`),
          all_listed_cases: replay.all_listed.cases_replayed,
          all_listed_share_pct: replay.all_listed.share_on_board_pct,
          bias_note: replay.bias_note,
          file: "data/replay.json",
        }
      : null,
    product: {
      reserve_months_min: 4,
      grace_days_default: 14,
      grace_days_max: 30,
      max_berths: 40,
      history_entries: 64,
    },
    deployment: deployment
      ? {
          network: deployment.network,
          portage: deployment.portage,
          allotment: deployment.allotment,
          tusd: deployment.tusd,
          registry: deployment.registry,
          registrar: deployment.registrar,
          hos_commit: deployment.hos_commit,
          code_hashes: deployment.code_hashes,
          access_keys: deployment.access_keys,
          file: "deployments/testnet.json",
        }
      : null,
    runs: runs ?? null,
  };
}

function main() {
  const facts = buildFacts();
  const text = JSON.stringify(facts, null, 2) + "\n";
  if (process.argv.includes("--check")) {
    const committed = existsSync("docs/FACTS.json") ? readFileSync("docs/FACTS.json", "utf8") : "";
    if (committed !== text) {
      console.error("FAIL facts: docs/FACTS.json is stale; run `npm run facts` and commit");
      process.exit(1);
    }
    console.log("PASS facts: docs/FACTS.json matches its sources");
    return;
  }
  writeFileSync("docs/FACTS.json", text);
  mkdirSync("app/lib/generated", { recursive: true });
  writeFileSync("app/lib/generated/facts.json", text);
  for (const [from, to] of [["deployments/testnet.json", "app/lib/generated/deployment.json"], ["data/replay.json", "app/lib/generated/replay.json"], ["data/runs.json", "app/lib/generated/runs.json"]]) {
    if (existsSync(from)) copyFileSync(from, to);
    else if (!existsSync(to)) writeFileSync(to, "null\n");
  }
  console.log("wrote docs/FACTS.json and app/lib/generated/*");
}

if (import.meta.url === `file://${process.argv[1]}`) main();
